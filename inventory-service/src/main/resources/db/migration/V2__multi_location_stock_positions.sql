CREATE TABLE IF NOT EXISTS stock_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(255) NOT NULL,
    location_id VARCHAR(255) NOT NULL,
    lot_id VARCHAR(255) NOT NULL DEFAULT 'DEFAULT',
    on_hand_quantity INT NOT NULL DEFAULT 0,
    reserved_quantity INT NOT NULL DEFAULT 0,
    safety_stock_quantity INT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_pos_sku_loc_lot UNIQUE (sku, location_id, lot_id)
);

CREATE INDEX IF NOT EXISTS idx_stock_pos_sku ON stock_positions(sku);
CREATE INDEX IF NOT EXISTS idx_stock_pos_loc ON stock_positions(location_id);

CREATE TABLE IF NOT EXISTS stock_position_buckets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(255) NOT NULL,
    location_id VARCHAR(255) NOT NULL,
    bucket_id INT NOT NULL,
    on_hand_quantity INT NOT NULL DEFAULT 0,
    reserved_quantity INT NOT NULL DEFAULT 0,
    safety_stock_quantity INT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_bucket_sku_loc_bkt UNIQUE (sku, location_id, bucket_id)
);

CREATE INDEX IF NOT EXISTS idx_stock_bucket_sku_loc ON stock_position_buckets(sku, location_id);

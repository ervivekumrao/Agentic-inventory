-- V3 Migration: Domain Expansion (Suppliers, Purchase Orders, Locations)

ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS reorder_threshold INT DEFAULT 10;

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    contact_email VARCHAR(128),
    lead_time_days INT DEFAULT 7,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_supplier_code ON suppliers(code);

CREATE TABLE IF NOT EXISTS locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    type VARCHAR(64) DEFAULT 'WAREHOUSE',
    capacity INT DEFAULT 10000
);

CREATE INDEX IF NOT EXISTS idx_location_code ON locations(code);

CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL UNIQUE,
    supplier_code VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    expected_delivery_date TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_po_number ON purchase_orders(order_number);
CREATE INDEX IF NOT EXISTS idx_po_status ON purchase_orders(status);

CREATE TABLE IF NOT EXISTS purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE CASCADE,
    sku VARCHAR(64) NOT NULL,
    ordered_quantity INT NOT NULL DEFAULT 1,
    received_quantity INT NOT NULL DEFAULT 0,
    unit_cost DOUBLE PRECISION DEFAULT 0.0
);

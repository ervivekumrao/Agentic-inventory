package com.smartinventory.inventory.dto;

public class MultiServiceLoggerDto {
    private String serviceId;
    private String serviceName;
    private String name;
    private String effectiveLevel;
    private String configuredLevel;

    public MultiServiceLoggerDto() {}

    public MultiServiceLoggerDto(String serviceId, String serviceName, String name, String effectiveLevel, String configuredLevel) {
        this.serviceId = serviceId;
        this.serviceName = serviceName;
        this.name = name;
        this.effectiveLevel = effectiveLevel;
        this.configuredLevel = configuredLevel;
    }

    public String getServiceId() {
        return serviceId;
    }

    public void setServiceId(String serviceId) {
        this.serviceId = serviceId;
    }

    public String getServiceName() {
        return serviceName;
    }

    public void setServiceName(String serviceName) {
        this.serviceName = serviceName;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEffectiveLevel() {
        return effectiveLevel;
    }

    public void setEffectiveLevel(String effectiveLevel) {
        this.effectiveLevel = effectiveLevel;
    }

    public String getConfiguredLevel() {
        return configuredLevel;
    }

    public void setConfiguredLevel(String configuredLevel) {
        this.configuredLevel = configuredLevel;
    }
}
